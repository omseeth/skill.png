"""The Benchmark contract: items, messages, scoring, and the rollout seam."""

from __future__ import annotations

import copy
import hashlib
from abc import ABC, abstractmethod
from dataclasses import dataclass, field

from torch import Tensor

from ..config import BenchmarkCfg
from ..models.base import VLM

Message = dict
SITES = ("pre_query", "post_query")


@dataclass
class Item:
    id: str
    target: str
    """Gold continuation for the training loss."""
    ground_truth: object = None
    group: str | None = None
    """Split unit. Source document, tool domain, task template — whatever items *share*. A universal image memorizes exactly that, so splitting on id
    leaks."""
    meta: dict = field(default_factory=dict)


@dataclass
class Result:
    item_id: str
    output: str
    score: float
    meta: dict = field(default_factory=dict)


class Benchmark(ABC):
    def __init__(self, cfg: BenchmarkCfg) -> None:
        """Store the benchmark configuration.

        Args:
            cfg: Benchmark configuration for this instance.
        """
        self.cfg = cfg

    @property
    def metric_name(self) -> str:
        """Name of the metric reported for this benchmark.

        Args:
            None.

        Returns:
            Metric name used in logs and results.
        """
        return "accuracy"

    @property
    def n_distractors(self) -> int | None:
        """Distractors offered per item, for benchmarks that have them.

        Returns:
            None, as a benchmark offers no distractors unless it says so.
        """
        return None

    @abstractmethod
    def items(self, split: str) -> list[Item]:
        """Items belonging to a split.

        Args:
            split: Name of the split to load.

        Returns:
            Items in that split.
        """

    @abstractmethod
    def build_messages(self, item: Item, with_image: bool, site: str = "pre_query") -> list[Message]:
        """Chat messages for this item, with an image slot at site when with_image.

        Open with system_messages() so the configured system turn is used, build the text, then
        call inject_image(messages, site) — do not hand-place image blocks.

        Args:
            item: Item to build the prompt for.
            with_image: Whether to reserve an image slot.
            site: Injection site for the image, pre_query or post_query.

        Returns:
            Chat messages for the item.
        """

    @abstractmethod
    def score(self, output: str, item: Item) -> float:
        """Score a model output against an item.

        Args:
            output: Text generated by the model.
            item: Item the output was generated for.

        Returns:
            Score for this output.
        """

    def system_messages(self) -> list[Message]:
        """The configured system turn, verbatim, or nothing when it is empty.

        Args:
            None.

        Returns:
            A one-message list, empty when benchmark.system_prompt is empty.
        """
        if not self.cfg.system_prompt:
            return []

        # A plain string, not text blocks: Nemotron's chat template renders
        # block-list system content as its Python repr. vLLM re-wraps it in
        # blocks, so its servers take slurm/chat_templates/ instead.
        return [{"role": "system", "content": self.cfg.system_prompt}]

    async def rollout(
        self, item: Item, model: VLM, image: Tensor | None, site: str = "pre_query"
    ) -> Result:
        """Default: build messages, generate, score.

        This is the entire agentic extension point. A tool-using benchmark overrides this method and nothing else; everything above it awaits a
        Result and does not care how it was made.

        Args:
            item: Item to roll out.
            model: Model used to generate the output.
            image: Image to inject, or None for a text-only rollout.
            site: Injection site for the image, pre_query or post_query.

        Returns:
            Result holding the output and its score.
        """
        messages = self.build_messages(item, with_image=image is not None, site=site)
        output = model.generate(messages, image)

        return Result(item_id=item.id, output=output, score=self.score(output, item))


def image_block() -> dict:
    """The content block HF chat templates expand into image placeholder tokens.

    Args:
        None.

    Returns:
        Content block marking an image position.
    """
    return {"type": "image"}


def inject_image(messages: list[Message], site: str = "pre_query") -> list[Message]:
    """Insert one image block at site in the last user message. Returns a copy; the input is not mutated.

    The image always rides in a user turn — chat templates do not expand image blocks in a system
    message. pre_query (the default) puts it immediately before the question. Everything *before*
    the image is recomputed on every optimization step, so a late image leaves a long constant
    prefix a future KV cache can reuse.

    Args:
        messages: Chat messages to inject into.
        site: Injection site for the image, pre_query or post_query.

    Returns:
        Copy of messages with one image block inserted.
    """
    if site not in SITES:
        raise ValueError(f"unknown injection site {site!r}; expected one of {SITES}")
    
    out = copy.deepcopy(messages)
    index = next((i for i in reversed(range(len(out))) if out[i].get("role") == "user"), None)

    if index is None:
        raise ValueError(f"site={site!r} needs a user message to attach the image to")

    content = out[index].get("content")

    if isinstance(content, str):
        content = [{"type": "text", "text": content}]
    elif isinstance(content, list):
        content = list(content)
    else:
        content = []

    if site == "post_query":
        content.append(image_block())
    else:
        content.insert(0, image_block())
    out[index]["content"] = content

    return out


def split_by_group(
    items: list[Item],
    fractions: dict[str, float],
    seed: int = 0,
    allow_ungrouped: bool = False,
) -> dict[str, list[Item]]:
    """Assign whole groups to splits, deterministically.

    A group never straddles a split boundary, so val/test cannot contain the structure the image memorized from train. Refuses ungrouped data unless you
    say otherwise, because splitting on item id looks fine and inflates every
    number.

    Args:
        items: Items to distribute across splits.
        fractions: Split name to fraction of groups, summing to 1.
        seed: Seed making the assignment reproducible.
        allow_ungrouped: Whether items without a group are accepted.

    Returns:
        Split name to the items assigned to it.
    """
    if not fractions:
        raise ValueError("no splits requested")
    
    total = sum(fractions.values())

    if abs(total - 1.0) > 1e-6:
        raise ValueError(f"split fractions must sum to 1, got {total}")
    
    if any(value < 0 for value in fractions.values()):
        raise ValueError("split fractions must be non-negative")

    ungrouped = [item.id for item in items if item.group is None]

    if ungrouped and not allow_ungrouped:
        raise ValueError(
            f"{len(ungrouped)} item(s) have group=None (e.g. {ungrouped[:3]}). A universal image "
            "memorizes what items share, so splitting on item id leaks it into val/test. Set "
            "Item.group to the shared unit (source document, tool domain, task template), or pass "
            "benchmark.allow_ungrouped=true if you are certain items share nothing."
        )

    names = list(fractions)
    edges: list[tuple[str, float]] = []
    cumulative = 0.0

    for name in names:
        cumulative += fractions[name]
        edges.append((name, cumulative))

    out: dict[str, list[Item]] = {name: [] for name in names}

    for item in items:
        key = item.group if item.group is not None else f"__ungrouped__:{item.id}"
        position = _unit_hash(f"{seed}:{key}")
        chosen = names[-1]

        for name, edge in edges:
            if position < edge:
                chosen = name
                break

        out[chosen].append(item)

    return out


def _unit_hash(key: str) -> float:
    """Stable hash of a group key into [0,1). hash() is salted per process; this is not.

    Args:
        key: Group key to hash.

    Returns:
        Position in the unit interval.
    """
    digest = hashlib.sha256(key.encode()).digest()[:8]
    
    return int.from_bytes(digest, "big") / 2**64
