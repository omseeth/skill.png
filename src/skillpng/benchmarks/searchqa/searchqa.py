"""SearchQA (Dunn et al., 2017): Jeopardy! clues answered over retrieved passages.

**The splits are fixed, not computed.** data/searchqa_id_split/{train,val,test}/items.json lists the exact key values of the 400 / 200 / 1400 questions this project runs on.

Every item is one direct chat exchange: the system turn from
benchmark.system_prompt, then the MRQA snippet block truncated at 6000 chars
and the question. The answer is read back from <answer> tags, which is also
the shape the training target is wrapped in.
"""

from __future__ import annotations

import json
import logging
import re
import string
from collections import Counter
from collections.abc import Iterator, Mapping, Sequence
from dataclasses import dataclass, fields
from datasets import load_dataset
from pathlib import Path

from ...config import BenchmarkCfg
from ..base import Benchmark, Item, Message, inject_image
from ..registry import BENCHMARKS

log = logging.getLogger(__name__)

METRICS = ("f1", "em")
HF_REPO = "lucadiliello/searchqa"
SPLIT_ROOT = Path(__file__).parent.parent / "data" / "searchqa_id_split"
SPLITS = ("train", "val", "test")

# The character budget the snippet block is cut back to, and the shape the
# gold answer is trained and scored in. Both are protocol, not preference:
# changing either makes scores incomparable with earlier runs.
MAX_CONTEXT_CHARS = 6000
ANSWER_TEMPLATE = "<answer>{answer}</answer>"


@dataclass(frozen=True)
class SearchQAOptions:
    """benchmark.options for this adapter. Unknown keys are rejected, as in the config schema."""

    metric: str = "f1"

    @classmethod
    def parse(cls, options: dict) -> SearchQAOptions:
        """Validate the raw options mapping and build the options object.

        Args:
            options: Raw benchmark.options mapping from the config.

        Returns:
            Parsed options with a metric known to METRICS.
        """
        known = {field.name for field in fields(cls)}
        unknown = sorted(set(options) - known)

        if unknown:
            raise ValueError(f"unknown searchqa option(s) {unknown}; expected {sorted(known)}")

        parsed = cls(**options)

        if parsed.metric not in METRICS:
            raise ValueError(f"metric={parsed.metric!r}; expected one of {METRICS}")

        return parsed


@BENCHMARKS.register("searchqa")
class SearchQA(Benchmark):
    def __init__(self, cfg: BenchmarkCfg) -> None:
        """Resolve the mirror repo and options; the corpus is loaded lazily.

        Args:
            cfg: Benchmark configuration for this instance.
        """
        super().__init__(cfg)
        self.repo_id = _repo_id(cfg.path)
        self.opts = SearchQAOptions.parse(cfg.options)
        self._splits: dict[str, list[Item]] | None = None

    @property
    def metric_name(self) -> str:
        """Name the selected metric goes by in logs and results.

        Args:
            None.

        Returns:
            exact_match for em, unigram_f1 for f1.
        """
        return "exact_match" if self.opts.metric == "em" else "unigram_f1"

    def items(self, split: str) -> list[Item]:
        """Items of one split, materializing every split on first use.

        Args:
            split: Name of the split to load.

        Returns:
            Items in that split, in manifest order.
        """
        if self._splits is None:
            # items() is called once per split by the training loop; scanning 134k questions for
            # the manifest ids is not a scan to repeat.
            self._splits = self._build_splits()

        if split not in self._splits:
            raise KeyError(f"unknown split {split!r}; have {sorted(self._splits)}")
        
        return self._splits[split]

    def build_messages(
        self, item: Item, with_image: bool, site: str = "pre_query"
    ) -> list[Message]:
        """The configured system turn plus the question, with an image slot at site when asked.

        Args:
            item: Item to build the prompt for.
            with_image: Whether to reserve an image slot.
            site: Injection site for the image, pre_query or post_query.

        Returns:
            Chat messages for the item.
        """
        messages = [*self.system_messages(), self._query(item)]

        return inject_image(messages, site) if with_image else messages

    def score(self, output: str, item: Item) -> float:
        """Score the extracted answer against the best accepted surface form.

        Args:
            output: Text generated by the model.
            item: Item the output was generated for.

        Returns:
            Exact match or unigram F1, depending on the metric option.
        """
        prediction = extract_answer(output)
        scorer = exact_match if self.opts.metric == "em" else token_f1
        # MRQA carries a list of accepted surface forms; the row is right if any of them is.
        return max(scorer(prediction, gold) for gold in _golds(item.ground_truth))

    def _query(self, item: Item) -> Message:
        """The user turn: the truncated snippet block, then the question.

        Args:
            item: Item to build the prompt for.

        Returns:
            One user message carrying the context and the question.
        """
        context = str(item.meta.get("context", ""))

        if not context:
            raise ValueError(
                f"searchqa record {item.id!r} has no context; every item is asked over the "
                "MRQA snippet block, so a mirror without it cannot be run"
            )

        user = f"## Context\n{truncate_context(context)}\n\n## Question\n{item.meta['question']}"

        return {"role": "user", "content": [{"type": "text", "text": user}]}

    def _build_splits(self) -> dict[str, list[Item]]:
        """The manifest's ids, materialized from the mirror in manifest order.

        Args:
            None.

        Returns:
            Split name to its items, capped by cfg.limit when set.
        """
        ids = {name: _split_ids(name) for name in SPLITS}
        wanted = {item_id for split_ids in ids.values() for item_id in split_ids}
        records = _records_by_id(self.repo_id, wanted)
        missing = sorted(wanted - set(records))

        if missing:
            raise ValueError(
                f"{len(missing)} of {len(wanted)} manifest id(s) are not in {self.repo_id!r} "
                f"(e.g. {missing[:3]}). The manifest indexes the `key` field of {HF_REPO}; another "
                f"mirror does not carry the same ids, and a partial split is not this split."
            )
        
        splits = {
            name: [self._to_item(records[item_id]) for item_id in split_ids]
            for name, split_ids in ids.items()
        }

        if self.cfg.limit:
            # A smoke-run cap: the prefix of each split in manifest order, so the same items are
            # taken every time. It changes the corpus size, not which split anything is in.
            splits = {name: split[: self.cfg.limit] for name, split in splits.items()}

        for name, split_items in splits.items():
            log.info("searchqa %s: %d items", name, len(split_items))

        return splits

    def _to_item(self, record: dict) -> Item:
        """Turn one mirror row into an Item, refusing rows the manifest cannot use.

        Args:
            record: Row of the mirror dataset.

        Returns:
            Item carrying the question, its accepted answers and the tagged target.
        """
        item_id = _record_id(record)
        question = _clean(record.get("question"))
        answers = _answers(record.get("answers"))

        if not question or not answers:
            # The split is fixed, so an unusable row is a broken corpus, not a row to drop.
            raise ValueError(
                f"searchqa record {item_id!r} has no usable question or answer; the id split names "
                f"it, so it cannot be silently dropped"
            )

        meta = {"question": question, "answers": answers}
        # The snippet block rides along raw: it is fed byte-for-byte, so
        # cleaning here would change the protocol.
        context = record.get("context")

        if isinstance(context, str) and context:
            meta["context"] = context

        return Item(
            id=item_id,
            # The loss is taken on the shape the prompt asks for and the
            # scorer reads back; ground_truth stays the bare surface forms.
            target=ANSWER_TEMPLATE.format(answer=answers[0]),
            ground_truth=answers,
            group=None,
            meta=meta,
        )


def _split_ids(split: str) -> list[str]:
    """The ids of one manifest split, in file order and de-duplicated.

    Args:
        split: Split name, which is also its directory under SPLIT_ROOT.

    Returns:
        Item ids listed by that split's items.json.
    """
    path = SPLIT_ROOT / split / "items.json"

    try:
        raw = json.loads(path.read_text())
    except FileNotFoundError as exc:
        raise FileNotFoundError(f"searchqa id split is missing {path}") from exc
    
    if not isinstance(raw, list):
        raise ValueError(f"{path}: expected a list of items, got {type(raw).__name__}")
    
    out: list[str] = []
    seen: set[str] = set()

    for entry in raw:
        item_id = str(entry.get("id", "")).strip() if isinstance(entry, Mapping) else ""
        if not item_id:
            raise ValueError(f"{path}: item without an `id` field")
        if item_id not in seen:
            seen.add(item_id)
            out.append(item_id)

    if not out:
        raise ValueError(f"{path}: no ids")
    
    return out


def _repo_id(path: str | None) -> str:
    """benchmark.path names the Hub repo; the hf: prefix is optional, empty means the mirror.

    Args:
        path: Configured benchmark path, possibly None or hf:-prefixed.

    Returns:
        Hub repo id to load, defaulting to HF_REPO.
    """
    text = (path or "").strip()

    if text.startswith("hf:"):
        text = text[3:].strip()

    return text or HF_REPO


def _load(repo_id: str) -> dict:
    """Every split of the Hub dataset, keyed by its Hub split name.

    Args:
        repo_id: Hub repo id to load.

    Returns:
        Hub split name.
    """
    log.info("searchqa: loading %s", repo_id)
    splits: dict = load_dataset(repo_id)

    return splits


def _records_by_id(repo_id: str, wanted: set) -> dict:
    """The rows the manifest names, keyed by id; every other row is dropped on the way past.

    Args:
        repo_id: Hub repo id to scan.
        wanted: Item ids the manifest asks for.

    Returns:
        Item id to its row, for the ids that were found.
    """
    out: dict[str, dict] = {}

    for record in _rows(_load(repo_id)):
        item_id = _record_id(record)

        if item_id in wanted and item_id not in out:
            out[item_id] = dict(record)

            if len(out) == len(wanted):
                break

    return out


def _rows(dataset: dict) -> Iterator[dict]:
    """Every shipped split end to end, in a fixed order.

    The rows stay an iterator rather than a list: the splits are lazy, and
    materializing 134k rows to name a return type would undo that.

    Args:
        dataset: Hub split name to its rows.

    Returns:
        Iterator over the rows of every split, split names sorted.
    """
    for name in sorted(dataset):
        yield from dataset[name]


def _answers(raw: object) -> list[str]:
    """Accepted surface forms, cleaned and de-duplicated with order preserved.

    MRQA stores a list even where SearchQA has one answer; a bare string loads too.

    Args:
        raw: Answer field of a row, a string or a sequence of them.

    Returns:
        Cleaned answers, empty when the row carries none.
    """
    values = [raw] if isinstance(raw, str) else raw if isinstance(raw, Sequence) else []
    out: list[str] = []

    for value in values:
        answer = _clean(value)
        if answer and answer not in out:
            out.append(answer)

    return out


def _clean(value: object) -> str:
    """Stringify a field, collapsing whitespace and trimming the ends.

    Args:
        value: Field value of a row, possibly None or empty.

    Returns:
        Cleaned text, empty for a missing value.
    """
    return re.sub(r"\s+", " ", str(value)).strip() if value not in (None, "") else ""


def _record_id(record: dict) -> str:
    """The row's id, which is what the manifest matches on: MRQA's `key`.

    Args:
        record: Row of the mirror dataset.

    Returns:
        Row id, empty when neither key nor id is set.
    """
    for field_name in ("key", "id"):
        given = record.get(field_name)

        if given not in (None, ""):
            return str(given).strip()
        
    return ""


def _golds(ground_truth: object) -> list[str]:
    """Item.ground_truth as a list of accepted answers, tolerating a bare string.

    Args:
        ground_truth: Gold field of an item, a string or a sequence of them.

    Returns:
        Accepted answers as strings, never empty.
    """
    if isinstance(ground_truth, str):
        return [ground_truth]
    
    if isinstance(ground_truth, Sequence):
        return [str(value) for value in ground_truth] or [""]
    
    return [str(ground_truth)]


_ARTICLES = re.compile(r"\b(a|an|the)\b")
_PUNCT = str.maketrans("", "", string.punctuation)
# A block holds no second opener, so a trace that only names the tag ("put
# it in <answer> tags") never swallows the real block after it.
_ANSWER_TAG = re.compile(r"<answer>((?:(?!<answer>).)*?)</answer>", re.DOTALL | re.IGNORECASE)
_THINK_END = "</think>"


def truncate_context(context: str, max_chars: int = MAX_CONTEXT_CHARS) -> str:
    """Truncate the snippet block at [DOC] boundaries.

    One quirk is deliberate: the leading split piece is empty, so the first
    kept document loses its [DOC] marker whenever truncation runs. Scores
    are only comparable across runs while this stays as it is.

    Args:
        context: Raw MRQA snippet block of one row.
        max_chars: Character budget the kept prefix must stay inside.

    Returns:
        The context, cut back at document boundaries when over budget.
    """
    if len(context) <= max_chars:
        return context

    docs = context.split("[DOC]")
    result = ""

    for doc in docs:
        candidate = result + "[DOC]" + doc if result else doc
        if len(candidate) > max_chars:
            break
        result = candidate

    if not result:
        result = context[:max_chars] + "\n...[truncated]"

    return result


def extract_answer(output: str) -> str:
    """The answer the prompt asks for: last tag, then last line.

    Anything up to the last </think> is dropped and the last tag wins, so a
    draft answer inside a reasoning block is never scored. The line fallback
    catches a model that answers without tagging.

    Args:
        output: Text generated by the model.

    Returns:
        Content of the last answer tag, else the last non-empty line, else
        the stripped output.
    """
    output = output.rsplit(_THINK_END, 1)[-1]
    matches = _ANSWER_TAG.findall(output)

    if matches:
        return str(matches[-1]).strip()

    lines = [line.strip() for line in output.strip().splitlines() if line.strip()]

    if lines:
        return lines[-1]

    return output.strip()


def normalize_answer(text: str) -> str:
    """SQuAD normalization, which SearchQA's own evaluation follows: casefold, drop
    punctuation and articles, collapse whitespace.

    Args:
        text: Answer text to normalize.

    Returns:
        Normalized text used by both scorers.
    """
    lowered = text.lower().translate(_PUNCT)
    return " ".join(_ARTICLES.sub(" ", lowered).split())


def exact_match(prediction: str, gold: str) -> float:
    """Whether the two answers agree after normalization.

    Args:
        prediction: Answer extracted from the model output.
        gold: One accepted surface form.

    Returns:
        1.0 on an exact match, 0.0 otherwise.
    """
    return float(normalize_answer(prediction) == normalize_answer(gold))


def token_f1(prediction: str, gold: str) -> float:
    """Unigram F1, the paper's headline metric alongside exact match.

    Args:
        prediction: Answer extracted from the model output.
        gold: One accepted surface form.

    Returns:
        F1 over normalized unigrams, between 0.0 and 1.0.
    """
    predicted_tokens = normalize_answer(prediction).split()
    gold_tokens = normalize_answer(gold).split()

    if not predicted_tokens or not gold_tokens:
        return float(predicted_tokens == gold_tokens)
    
    overlap = sum((Counter(predicted_tokens) & Counter(gold_tokens)).values())

    if overlap == 0:
        return 0.0
    
    precision = overlap / len(predicted_tokens)
    recall = overlap / len(gold_tokens)
    
    return 2 * precision * recall / (precision + recall)
