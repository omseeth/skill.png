"""LiveMathematicianBench: multiple-choice questions on theorems from new arXiv papers.

**The splits are fixed, not computed.**
data/livemathematicianbench_id_split/{train,val,test}/items.json lists the
exact 73 / 33 / 239 records this project runs on, as <month>:<no> ids. The
records are read from the manifest's source_files at its pinned
source_revision. The default config at main grows every month, so it is never
loaded. Records with the stronger-result shortcut option are filtered out of
the split; see split_manifest.json.

Every item is one direct chat exchange: the system turn from
benchmark.system_prompt, then the question and its five choices. The theorem
and the proof sketch the source ships with each record are never shown,
because they give the answer away. The answer is read back from <answer> tags,
which is also the shape the training target is wrapped in.

The source lists the correct choice first, as A, in every record. The options
are therefore shown in a per-item order fixed by a hash of the id and
relabelled A-E, with the gold and the meta labels remapped to match. Shown as
shipped, a universal image could score 100% by learning to answer A.
"""

from __future__ import annotations

import json
import logging
import re
from pathlib import Path

from huggingface_hub import hf_hub_download

from ...config import BenchmarkCfg
from ..base import Benchmark, Item, Message, _unit_hash, inject_image
from ..registry import BENCHMARKS

log = logging.getLogger(__name__)

HF_REPO = "LiveMathematicianBench/LiveMathematicianBench"
SPLIT_ROOT = Path(__file__).parent.parent / "data" / "livemathematicianbench_id_split"
SPLITS = ("train", "val", "test")
LABELS = ("A", "B", "C", "D", "E")
# Manifest fields every record is checked against.
ENTRY_FIELDS = ("month", "no", "paper_link", "source_file")

# The shape the gold label is trained and scored in, and the seed of the
# per-item option order. Both are protocol: changing either one reshapes or
# reorders every item and breaks comparability with earlier runs.
ANSWER_TEMPLATE = "<answer>{label}</answer>"
PERMUTATION_SEED = 0

# A block holds no second opener, so a trace that only names the tag ("put
# it in <answer> tags") never swallows the real block after it.
_ANSWER_TAG = re.compile(r"<answer>((?:(?!<answer>).)*?)</answer>", re.DOTALL | re.IGNORECASE)
_THINK_END = "</think>"
# One label, optionally wrapped in whitespace, parentheses or bold markers,
# optionally followed by a period.
_LONE_LABEL = re.compile(r"[\s(*]*([A-E])[\s)*]*\.?[\s)*]*")


@BENCHMARKS.register("livemathematicianbench")
class LiveMathematicianBench(Benchmark):
    def __init__(self, cfg: BenchmarkCfg) -> None:
        """Resolve the Hub repo and refuse options; the records are loaded lazily.

        Args:
            cfg: Benchmark configuration for this instance.
        """
        super().__init__(cfg)

        if cfg.options:
            raise ValueError(f"livemathematicianbench takes no options, got {sorted(cfg.options)}")

        self.repo_id = _repo_id(cfg.path)
        self._splits: dict[str, list[Item]] | None = None

    def items(self, split: str) -> list[Item]:
        """Items of one split, materializing every split on first use.

        Args:
            split: Name of the split to load.

        Returns:
            Items in that split, in manifest order.
        """
        if self._splits is None:
            self._splits = self._build_splits()

        if split not in self._splits:
            raise KeyError(f"unknown split {split!r}; have {sorted(self._splits)}")

        return self._splits[split]

    def build_messages(
        self, item: Item, with_image: bool, site: str = "pre_query"
    ) -> list[Message]:
        """The configured system turn plus the question, with an image slot at site when asked.

        Args:
            item: Item to build the prompt for.
            with_image: Whether to reserve an image slot.
            site: Injection site for the image, pre_query or post_query.

        Returns:
            Chat messages for the item.
        """
        messages = [*self.system_messages(), self._query(item)]

        return inject_image(messages, site) if with_image else messages

    def score(self, output: str, item: Item) -> float:
        """Accuracy: whether the extracted label is the gold one.

        Args:
            output: Text generated by the model.
            item: Item the output was generated for.

        Returns:
            1.0 for the gold label, 0.0 otherwise.
        """
        return float(extract_label(output) == item.ground_truth)

    def _query(self, item: Item) -> Message:
        """The user turn: the question, then the choices under their shown labels.

        Args:
            item: Item to build the prompt for.

        Returns:
            One user message carrying the question and the choices.
        """
        choices = "\n".join(
            f"{option['label']}. {option['text']}" for option in item.meta["options"]
        )
        user = f"## Question\n{item.meta['question']}\n\n## Choices\n{choices}"

        return {"role": "user", "content": [{"type": "text", "text": user}]}

    def _build_splits(self) -> dict[str, list[Item]]:
        """The manifest's ids, materialized from the pinned files in manifest order.

        Args:
            None.

        Returns:
            Split name to its items, capped by cfg.limit when set.
        """
        manifest = _manifest()
        revision = str(manifest["source_revision"])
        source_files = [str(name) for name in manifest["source_files"]]
        entries = {name: _split_entries(name) for name in SPLITS}

        for split_entries in entries.values():
            for entry in split_entries:
                if entry.get("source_file") not in source_files:
                    raise ValueError(
                        f"livemathematicianbench entry {entry['id']!r} names source_file "
                        f"{entry.get('source_file')!r}, which the manifest's source_files do "
                        "not list"
                    )

        records = _records_by_id(self.repo_id, revision, source_files)
        wanted = [entry["id"] for split in entries.values() for entry in split]
        missing = sorted(item_id for item_id in wanted if item_id not in records)

        if missing:
            raise ValueError(
                f"{len(missing)} of {len(wanted)} manifest id(s) are not in {self.repo_id!r} "
                f"at revision {revision} (e.g. {missing[:3]}). A partial split is not this "
                "split."
            )

        splits = {
            name: [self._to_item(entry, *records[entry["id"]]) for entry in split]
            for name, split in entries.items()
        }

        if self.cfg.limit:
            # A smoke-run cap: the prefix of each split in manifest order, so
            # the same items are taken every time.
            splits = {name: split[: self.cfg.limit] for name, split in splits.items()}

        for name, split_items in splits.items():
            log.info("livemathematicianbench %s: %d items", name, len(split_items))

        return splits

    def _to_item(self, entry: dict, source_file: str, record: dict) -> Item:
        """Turn one manifest entry and its record into an Item with permuted choices.

        Args:
            entry: Manifest entry naming the id and the fields to check.
            source_file: Source file the record was read from.
            record: Record of the source file.

        Returns:
            Item carrying the shown choices, the gold label and the tagged target.
        """
        item_id = entry["id"]

        for name in ENTRY_FIELDS:
            actual = source_file if name == "source_file" else record.get(name)

            if entry.get(name) != actual:
                # The split is fixed, so a record that no longer matches the
                # manifest is a broken corpus, not a record to drop.
                raise ValueError(
                    f"livemathematicianbench record {item_id!r} has {name}={actual!r}, "
                    f"manifest says {entry.get(name)!r}"
                )

        mcq = record["mcq"]
        source = [mcq["correct_choice"], *mcq["choices"]]
        labels = [option["label"] for option in source]
        flags = mcq["meta"]
        flagged = {flags["weaker_true_label"], flags["wildcard_false_label"]}
        flagged.update(flags["false_labels"])

        if tuple(sorted(labels)) != LABELS or not flagged <= set(LABELS):
            raise ValueError(
                f"livemathematicianbench record {item_id!r} has option labels {labels} and "
                f"meta labels {sorted(flagged)}; expected exactly {list(LABELS)}"
            )

        shown = present_options(item_id, source)
        relabel = {option["label"]: LABELS[index] for index, option in enumerate(shown)}
        gold = relabel[mcq["correct_choice"]["label"]]

        return Item(
            id=item_id,
            # The loss is taken on the shape the prompt asks for and the
            # scorer reads back; ground_truth stays the bare label.
            target=ANSWER_TEMPLATE.format(label=gold),
            ground_truth=gold,
            group=record["paper_link"],
            meta={
                # evaluate.py copies meta["question"] into the per-item log.
                # Texts are verbatim but for the ends: the LaTeX in them
                # carries meaningful newlines.
                "question": str(mcq["question"]).strip(),
                "options": [
                    {"label": relabel[option["label"]], "text": str(option["text"]).strip()}
                    for option in shown
                ],
                "month": record["month"],
                "paper_link": record["paper_link"],
                "theorem_type": record["theorem_type"],
                "weaker_true_label": relabel[flags["weaker_true_label"]],
                "false_labels": sorted(relabel[label] for label in flags["false_labels"]),
                "wildcard_false_label": relabel[flags["wildcard_false_label"]],
            },
        )


def present_options(item_id: str, options: list[dict]) -> list[dict]:
    """The options in the order they are shown for one item.

    Each option is ranked by a sha256 of PERMUTATION_SEED, the item id and its
    source label, so the order depends on those three and nothing else.

    Args:
        item_id: Id of the item the options belong to.
        options: Options as shipped, each with a source label.

    Returns:
        The same options in their shown order.
    """
    return sorted(
        options,
        key=lambda option: _unit_hash(f"{PERMUTATION_SEED}:{item_id}:{option['label']}"),
    )


def extract_label(output: str) -> str | None:
    """The choice label inside the last answer tag, when that is all the tag holds.

    Anything up to the last </think> is dropped and the last tag wins, so a
    draft answer made while reasoning is never scored. There is no fallback:
    a trace cut off at max_new_tokens can end on a line that reads A, which
    is not an answer.

    Args:
        output: Text generated by the model.

    Returns:
        A label from A to E, or None when there is no single one.
    """
    output = output.rsplit(_THINK_END, 1)[-1]
    matches = _ANSWER_TAG.findall(output)

    if not matches:
        return None

    lone = _LONE_LABEL.fullmatch(matches[-1])

    return lone.group(1) if lone else None


def record_id(record: dict) -> str:
    """The id a record goes by in the manifest, <month>:<no>.

    Args:
        record: Record of a source file.

    Returns:
        The record's id.
    """
    return f"{record.get('month')}:{record.get('no')}"


def _repo_id(path: str | None) -> str:
    """benchmark.path names the Hub repo; the hf: prefix is optional, empty means HF_REPO.

    Args:
        path: Configured benchmark path, possibly None or hf:-prefixed.

    Returns:
        Hub repo id to download from, defaulting to HF_REPO.
    """
    text = (path or "").strip()

    if text.startswith("hf:"):
        text = text[3:].strip()

    return text or HF_REPO


def _manifest() -> dict:
    """The shipped split manifest, which pins the source revision and files.

    Args:
        None.

    Returns:
        The manifest mapping.
    """
    path = SPLIT_ROOT / "split_manifest.json"

    try:
        document: dict = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise FileNotFoundError(f"livemathematicianbench id split is missing {path}") from exc

    return document


def _split_entries(split: str) -> list[dict]:
    """The entries of one manifest split, in file order and de-duplicated.

    Args:
        split: Split name, which is also its directory under SPLIT_ROOT.

    Returns:
        Manifest entries listed by that split's items.json.
    """
    path = SPLIT_ROOT / split / "items.json"

    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise FileNotFoundError(f"livemathematicianbench id split is missing {path}") from exc

    if not isinstance(raw, list):
        raise ValueError(f"{path}: expected a list of items, got {type(raw).__name__}")

    out: list[dict] = []
    seen: set[str] = set()

    for entry in raw:
        item_id = str(entry.get("id", "")).strip() if isinstance(entry, dict) else ""

        if not item_id:
            raise ValueError(f"{path}: item without an id field")

        if item_id not in seen:
            seen.add(item_id)
            out.append(dict(entry))

    if not out:
        raise ValueError(f"{path}: no ids")

    return out


def _load(repo_id: str, revision: str, source_file: str) -> list[dict]:
    """One source file of the Hub dataset at the pinned revision.

    Args:
        repo_id: Hub repo id to download from.
        revision: Commit the manifest pins.
        source_file: Path of the file inside the repo.

    Returns:
        The records the file lists.
    """
    path = hf_hub_download(repo_id, source_file, repo_type="dataset", revision=revision)
    raw = json.loads(Path(path).read_text(encoding="utf-8"))

    if not isinstance(raw, list):
        raise ValueError(f"{source_file}: expected a list of records, got {type(raw).__name__}")

    return raw


def _records_by_id(repo_id: str, revision: str, source_files: list[str]) -> dict:
    """Every record of the pinned files, keyed by id, with the file it came from.

    Args:
        repo_id: Hub repo id to download from.
        revision: Commit the manifest pins.
        source_files: Files to read, in manifest order.

    Returns:
        Item id to its source file and record.
    """
    out: dict = {}

    for source_file in source_files:
        for record in _load(repo_id, revision, source_file):
            item_id = record_id(record)

            if item_id in out:
                raise ValueError(
                    f"livemathematicianbench record {item_id!r} occurs in both "
                    f"{out[item_id][0]} and {source_file}"
                )

            out[item_id] = (source_file, record)

    return out
