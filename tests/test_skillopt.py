@needs_anthropic
def test_an_anthropic_refusal_is_logged_as_failed_and_retried(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    import httpx2
    from skillopt.model import azure_openai

    monkeypatch.setattr(azure_openai, "chat_optimizer", azure_openai.chat_optimizer)
    replies = iter(["refusal", "end_turn"])

    def serve(request: httpx2.Request) -> object:
        """Decline once, then answer.

        Args:
            request: The request.

        Returns:
            The streamed message.
        """
        return _sse(_message_events(1, "claude-sonnet-5-5", "ok", next(replies)))

    log = openrouter.CallLog(tmp_path / "calls.jsonl")
    transport = httpx2.MockTransport(serve)  # type: ignore[arg-type]
    anthropic_api.install(anthropic_api.API, KEY, "claude-sonnet-5-5", "high", log, transport)
    monkeypatch.setattr(time, "sleep", lambda seconds: None)
    text, usage = azure_openai.chat_optimizer(system="Stage one.\nMore.", user="u")

    assert text == "ok" and usage["completion_tokens"] == 20
    entries = [json.loads(line) for line in log.path.read_text().splitlines()]
    assert [e["finish_reason"] for e in entries] == ["refusal", "end_turn"]
    assert entries[0]["error"] == "refusal: frontier_llm"
    assert {e["stage"] for e in entries} == {"Stage one."}
    assert (log.totals()["calls"], log.totals()["failed"]) == (2, 1)


@needs_openai
def test_an_interrupted_step_resumes_without_redoing_completed_steps(tmp_path: Path) -> None:
    first = FakeOpenRouter()

    with pytest.raises(RuntimeError, match="the target went away"):
        _train(tmp_path, Oracle(crash_on_bad=True), first)

    run_path = _run_path(tmp_path)
    state = json.loads((run_path / "runtime_state.json").read_text())
    assert state["last_completed_step"] == 1
    assert first.stages() == ["failure", "success"]

    second = FakeOpenRouter()
    oracle = Oracle()
    dest = _train(tmp_path, oracle, second, resume=True)
    history = json.loads((run_path / "history.json").read_text())

    assert [h["step"] for h in history] == [1, 2]
    assert history[1]["action"] == "reject"
    # Step 2's reflection was saved before the crash and is reused.
    assert second.stages() == ["slow", "meta"]
    # Neither the seed's baseline nor step 1 is rolled out again.
    assert all(GOOD in _text(messages[0]) for messages in oracle.seen)
    run = json.loads((run_path / "run.json").read_text())
    assert len(run["resumed_utc"]) == 1
    assert dest is not None and GOOD in (dest / "skill.md").read_text()


