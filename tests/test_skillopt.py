def _result(benchmark: Benchmark, item: Item, output: str) -> Result:
    """Score an output the way the benchmark's rollout does.

    Args:
        benchmark: The benchmark.
        item: The item.
        output: The model's output.

    Returns:
        The result, with the breakdown in meta where the benchmark has one.
    """
    breakdown = getattr(benchmark, "breakdown", None)
    meta = breakdown(output, item) if callable(breakdown) else {}
    return Result(item_id=item.id, output=output, score=benchmark.score(output, item), meta=meta)


