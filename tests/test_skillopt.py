    assert meta["val"]["seed_skill"]["hard"] == 0.0
    assert meta["val"]["selected_skill"]["hard"] == 1.0
    assert (meta["steps"]["accepted"], meta["steps"]["rejected"]) == (1, 1)
    assert meta["hyperparameters"]["eval_test"] is False
    assert meta["hyperparameters"]["gate_metric"] == "hard"
    assert meta["target"]["chat_template_kwargs"] == {"enable_thinking": False}
    assert meta["optimizer_usage"]["calls"] == 4
    assert meta["optimizer_usage"]["cost_usd"] == pytest.approx(1.0)
