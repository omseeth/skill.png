def test_the_executor_pool_never_lends_one_executor_to_two_threads() -> None:
    class Slow(Executor):
        """An executor that notices being used twice at once."""

        def __init__(self) -> None:
            """Start idle.

            Args:
                None.
            """
            super().__init__("/nowhere")
            self.busy = False
            self.overlaps = 0
            self.calls = 0

        def execute(
            self,
            replay: list[str],
            gold: str | None,
            code: str,
            timeout_s: float,
            strict: bool = True,
        ) -> Outcome:
            """Hold the executor briefly.

            Args:
                replay: Ignored.
                gold: Ignored.
                code: Ignored.
                timeout_s: Ignored.
                strict: Ignored.

            Returns:
                An empty outcome.
            """
            self.overlaps += int(self.busy)
            self.busy = True
            time.sleep(0.01)
            self.calls += 1
            self.busy = False
            return Outcome("", "success", "", {}, "success", "", {}, False, True, [])

    members = [Slow() for _ in range(3)]
    pool = skillopt_adapter.ExecutorPool(list(members))
    threads = [threading.Thread(target=pool.execute, args=([], None, "", 1.0)) for _ in range(12)]

    for thread in threads:
        thread.start()

    for thread in threads:
        thread.join()

    assert sum(m.calls for m in members) == 12
    assert sum(m.overlaps for m in members) == 0


def test_the_preflight_fails_fast_with_a_clear_message() -> None:
    def serve(models: list[dict[str, object]], key_status: int = 200) -> httpx.MockTransport:
        """A fake OpenRouter answering /key and /models.

        Args:
            models: The model list.
            key_status: Status of the key lookup.

        Returns:
            The transport.
        """

        def handler(request: httpx.Request) -> httpx.Response:
            """Answer one request.

            Args:
                request: The request.

            Returns:
                The response.
            """
            if request.url.path.endswith("/key"):
                return httpx.Response(key_status, json={"data": {}})
            return httpx.Response(200, json={"data": models})

        return httpx.MockTransport(handler)

    model: dict[str, object] = {
        "id": "openai/gpt-5.5",
        "supported_parameters": ["reasoning_effort"],
    }
    openrouter.preflight(openrouter.API, KEY, "openai/gpt-5.5", "medium", serve([model]))

    with pytest.raises(SystemExit, match="refused the API key"):
        openrouter.preflight(openrouter.API, KEY, "openai/gpt-5.5", "medium", serve([model], 401))

    with pytest.raises(SystemExit, match="lists no model"):
        openrouter.preflight(openrouter.API, KEY, "openai/gpt-9", "medium", serve([model]))

    plain: dict[str, object] = {"id": "openai/gpt-5.5", "supported_parameters": []}
    with pytest.raises(SystemExit, match="reasoning_effort"):
        openrouter.preflight(openrouter.API, KEY, "openai/gpt-5.5", "medium", serve([plain]))

    def unreachable(request: httpx.Request) -> httpx.Response:
        """Fail like a node without outbound internet.

        Args:
            request: The request.

        Returns:
            Never returns.
        """
        raise httpx.ConnectError("no route to host")

    with pytest.raises(SystemExit, match="HTTPS_PROXY"):
        openrouter.preflight(
            openrouter.API, KEY, "openai/gpt-5.5", "medium", httpx.MockTransport(unreachable)
        )


