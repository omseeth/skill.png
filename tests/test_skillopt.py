@BENCHMARKS.register("_test_skillopt")
class Toy(Benchmark):
    """Four train, four val and two test items, each split's text marked."""

    def items(self, split: str) -> list[Item]:
        """The items of one split.

        Args:
            split: train, val or test.

        Returns:
            Items whose gold answer is yes.
        """
        count = {"train": 4, "val": 4, "test": 2}[split]
        mark = {"train": "TRAIN-TEXT", "val": "VAL-SECRET", "test": "TEST-SECRET"}[split]

        return [
            Item(
                id=f"{split}{i}",
                target="yes",
                ground_truth="yes",
                meta={"question": f"{mark}-{i}: is this a question?"},
            )
            for i in range(count)
        ]

    def build_messages(
        self, item: Item, with_image: bool, site: str = "pre_query"
    ) -> list[dict[str, object]]:
        """The configured system turn, then the item's question.

        Args:
            item: Item to build the prompt for.
            with_image: Whether to reserve an image slot.
            site: Injection site for the image.

        Returns:
            Chat messages for the item.
        """
        text = str(item.meta["question"])
        query = {"role": "user", "content": [{"type": "text", "text": text}]}
        messages = [*self.system_messages(), query]

        return inject_image(messages, site) if with_image else messages

    def score(self, output: str, item: Item) -> float:
        """Whether the output is the gold answer.

        Args:
            output: Text generated by the model.
            item: Item the output was generated for.

        Returns:
            1.0 on a match, 0.0 otherwise.
        """
        return float(output == item.ground_truth)


class Oracle(VLM):
    """Answers yes exactly when its system turn holds the good rule and not the bad one."""

    def __init__(self, crash_on_bad: bool = False) -> None:
        """Start with no prompts seen.

        Args:
            crash_on_bad: Raise on the first prompt carrying the bad rule.
        """
        self.seen: list[list[dict[str, object]]] = []
        self.images: list[Tensor | None] = []
        self.crash_on_bad = crash_on_bad
        self._lock = threading.Lock()

    def loss_on_target(
        self, messages: list[dict[str, object]], image: Tensor | None, target: str
    ) -> Tensor:
        """Refuse: nothing is trained here.

        Args:
            messages: Chat turns.
            image: Image, or None.
            target: Gold continuation.

        Returns:
            Never returns.
        """
        raise NotImplementedError

    def generate(
        self, messages: list[dict[str, object]], image: Tensor | None, **kw: object
    ) -> str:
        """Record the prompt and answer from the skill alone.

        Args:
            messages: Chat turns.
            image: Image, or None.
            **kw: Generation overrides, ignored.

        Returns:
            yes or no.
        """
        system = _text(messages[0])

        with self._lock:
            self.seen.append(messages)
            self.images.append(image)

        if BAD in system and self.crash_on_bad:
            raise RuntimeError("the target went away")

        return "yes" if GOOD in system and BAD not in system else "no"

    @property
    def preprocess(self) -> PreprocessSpec:
        """A fixed spec; nothing here reads it.

        Args:
            None.

        Returns:
            A 16x16 spec.
        """
        return PreprocessSpec(height=16, width=16)


class FakeOpenRouter:
    """OpenRouter's chat completions, answering each SkillOpt stage in upstream's format."""

    def __init__(self) -> None:
        """Start with no requests seen.

        Args:
            None.
        """
        self.requests: list[dict[str, object]] = []
        self.unexpected: list[str] = []
        self._lock = threading.Lock()

    def __call__(self, request: object) -> object:
        """Answer one request.

        Args:
            request: The SDK's outgoing request.

        Returns:
            A chat completion.
        """
        import httpx2

        assert isinstance(request, httpx2.Request)
        body = json.loads(request.content)
        system = str(body["messages"][0]["content"])
        user = str(body["messages"][1]["content"])

        with self._lock:
            self.requests.append(
                {
                    "system": system,
                    "user": user,
                    "body": body,
                    "authorization": request.headers.get("authorization"),
                }
            )
            index = len(self.requests)

        payload = {
            "id": f"gen-{index}",
            "object": "chat.completion",
            "created": 0,
            "model": body["model"],
            "provider": "FakeProvider",
            "choices": [
                {
                    "index": 0,
                    "message": {
                        "role": "assistant",
                        "content": json.dumps(self.reply(system, user)),
                    },
                    "finish_reason": "stop",
                }
            ],
            "usage": {
                "prompt_tokens": 100,
                "completion_tokens": 20,
                "total_tokens": 120,
                "cost": 0.25,
                "completion_tokens_details": {"reasoning_tokens": 7},
            },
        }

        return httpx2.Response(200, json=payload)

    def reply(self, system: str, user: str) -> dict[str, object]:
        """The canned answer for one stage.

        Args:
            system: The stage's system prompt.
            user: The stage's user message.

        Returns:
            The JSON object the stage expects.
        """
        if "failure-analysis" in system:
            edits = [] if GOOD in user else [{"op": "append", "content": GOOD}]
            return {
                "batch_size": 4,
                "failure_summary": [],
                "patch": {"reasoning": "r", "edits": edits},
            }

        if "success-pattern" in system:
            edits = [{"op": "append", "content": BAD}]
            return {
                "batch_size": 4,
                "success_patterns": [],
                "patch": {"reasoning": "r", "edits": edits},
            }

        if "slow_update_content" in system:
            return {"reasoning": "r", "slow_update_content": "SLOW-GUIDANCE"}

        if "meta_skill_content" in system:
            return {"reasoning": "r", "meta_skill_content": "META-NOTES"}

        self.unexpected.append(system.splitlines()[0])
        return {}

    def stages(self) -> list[str]:
        """The stage of every request, in order.

        Args:
            None.

        Returns:
            failure, success, slow or meta per request.
        """
        names = {
            "failure-analysis": "failure",
            "success-pattern": "success",
            "slow_update_content": "slow",
            "meta_skill_content": "meta",
        }

        return [
            next((name for marker, name in names.items() if marker in str(r["system"])), "?")
            for r in self.requests
        ]


def _sse(events: list[dict[str, object]]) -> object:
    """A streamed Messages response carrying the given events.

    Args:
        events: The server-sent events, each with its type.

    Returns:
        The response.
    """
    import httpx2

    body = "".join(f"event: {e['type']}\ndata: {json.dumps(e)}\n\n" for e in events)

    return httpx2.Response(
        200, headers={"content-type": "text/event-stream"}, content=body.encode()
    )


def _message_events(
    index: int, model: str, text: str, stop_reason: str = "end_turn"
) -> list[dict[str, object]]:
    """The events of one streamed reply: 100 tokens in, 20 out.

    Args:
        index: Number of the request, which names the message.
        model: The model that answers.
        text: The reply's text.
        stop_reason: Why the reply ended.

    Returns:
        The events, in order.
    """
    message: dict[str, object] = {
        "id": f"msg_{index}",
        "type": "message",
        "role": "assistant",
        "model": model,
        "content": [],
        "stop_reason": None,
        "stop_sequence": None,
        "usage": {"input_tokens": 100, "output_tokens": 1},
    }
    delta: dict[str, object] = {"stop_reason": stop_reason, "stop_sequence": None}

    if stop_reason == "refusal":
        delta["stop_details"] = {"type": "refusal", "category": "frontier_llm"}

    return [
        {"type": "message_start", "message": message},
        {"type": "content_block_start", "index": 0, "content_block": {"type": "text", "text": ""}},
        {"type": "content_block_delta", "index": 0, "delta": {"type": "text_delta", "text": text}},
        {"type": "content_block_stop", "index": 0},
        {"type": "message_delta", "delta": delta, "usage": {"output_tokens": 20}},
        {"type": "message_stop"},
    ]


class FakeAnthropic(FakeOpenRouter):
    """Anthropic's streamed Messages API, answering each stage as FakeOpenRouter does."""

    def __call__(self, request: object) -> object:
        """Answer one request.

        Args:
            request: The SDK's outgoing request.

        Returns:
            A streamed message.
        """
        import httpx2

        assert isinstance(request, httpx2.Request)
        body = json.loads(request.content)
        system = str(body["system"])
        user = str(body["messages"][0]["content"])

        with self._lock:
            self.requests.append(
                {
                    "system": system,
                    "user": user,
                    "body": body,
                    "authorization": request.headers.get("x-api-key"),
                }
            )
            index = len(self.requests)

        text = json.dumps(self.reply(system, user))

        return _sse(_message_events(index, body["model"], text))


def _text(message: dict[str, object]) -> str:
    """The text of a message: a plain string, or its first content block.

    Args:
        message: One chat message.

    Returns:
        Its text.
    """
    content = message["content"]
    if isinstance(content, str):
        return content
    assert isinstance(content, list) and isinstance(content[0], dict)
    return str(content[0]["text"])


def _config(tmp_path: Path, **eval_: object) -> Config:
    """A toy target config with its run under tmp_path.

    Args:
        tmp_path: Directory the run lands in.
        **eval_: Overrides of the eval section.

    Returns:
        The validated config, thinking off.
    """
    return Config.model_validate(
        {
            "model": {"name": "vllm", "chat_template_kwargs": {"enable_thinking": False}},
            "benchmark": {"name": "_test_skillopt", "system_prompt": PROMPT},
            "train": {"run_dir": str(tmp_path / "runs" / "toy" / "toy-model"), "run_name": "t"},
            "eval": eval_,
            "results": {"path": str(tmp_path / "results.jsonl")},
        }
    )


def _options(tmp_path: Path, **changes: object) -> skillopt_train.Options:
    """Options for a two-epoch run over the four train items in one batch.

    Args:
        tmp_path: Directory the seed skill is written to.
        **changes: Fields to change.

    Returns:
        The options.
    """
    seed = tmp_path / "seed.md"
    seed.write_text(SEED)
    fields: dict[str, object] = {
        "init_skill": seed,
        "workers": 4,
        "skillopt": {"num_epochs": 2, "batch_size": 4},
        **changes,
    }

    return skillopt_train.Options(**fields)  # type: ignore[arg-type]


def _train(tmp_path: Path, model: VLM, optimizer: FakeOpenRouter, **changes: object) -> Path | None:
    """One offline training run.

    Args:
        tmp_path: Directory of the run and the frozen tree.
        model: The target.
        optimizer: The fake OpenRouter.
        **changes: Option fields to change.

    Returns:
        Where the selected skill landed.
    """
    import httpx2

    return skillopt_train.run(
        _config(tmp_path),
        _options(tmp_path, **changes),
        api_key=KEY,
        model=model,
        transport=httpx2.MockTransport(optimizer),  # type: ignore[arg-type]
        check_endpoints=False,
        skills_root=tmp_path / "skills",
    )


def _run_path(tmp_path: Path) -> Path:
    """The toy run's directory.

    Args:
        tmp_path: The test's directory.

    Returns:
        The run directory.
    """
    return _config(tmp_path).run_path.resolve()


