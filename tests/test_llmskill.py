@pytest.mark.parametrize("path", EXPERIMENT_CONFIGS, ids=lambda p: p.name)
def test_the_skill_follows_the_unedited_prompt_of_every_shipped_config(path: Path) -> None:
    """The answer format stays in place, and the skill comes after it.

    Args:
        path: One experiment config.
    """
    cfg = load_config(path)
    composed = compose_system_prompt(
        cfg.benchmark.system_prompt, cfg.injection.skill_template, SKILL
    )

    assert composed.startswith(cfg.benchmark.system_prompt)
    assert composed.endswith(f"## Skill\n{SKILL}\n")
    # T1 keeps upstream's one-line system turn and its answer format in the
    # user turn, which the skill never touches.
    expected = 0 if cfg.benchmark.name == "t1" else 1
    assert composed.count("## Answer Format") == expected


