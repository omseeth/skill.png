class Recorder(VLM):
    """Answers yes to everything and keeps every prompt and image it was shown."""

    def __init__(self) -> None:
        """Start with no prompts or images seen.

        Args:
            None.
        """
        self.seen: list[list[dict[str, object]]] = []
        self.images: list[Tensor | None] = []

    def loss_on_target(
        self, messages: list[dict[str, object]], image: Tensor | None, target: str
    ) -> Tensor:
        """Refuse: nothing is trained here.

        Args:
            messages: Chat turns.
            image: Image, or None.
            target: Gold continuation.

        Returns:
            Never returns.
        """
        raise NotImplementedError

    def generate(
        self, messages: list[dict[str, object]], image: Tensor | None, **kw: object
    ) -> str:
        """Record the prompt and the image, and answer yes.

        Args:
            messages: Chat turns.
            image: Image, or None.
            **kw: Generation overrides, ignored.

        Returns:
            Always yes.
        """
        self.seen.append(messages)
        self.images.append(image)
        return "yes"

    @property
    def preprocess(self) -> PreprocessSpec:
        """A fixed spec; nothing here reads it.

        Args:
            None.

        Returns:
            A 16x16 spec.
        """
        return PreprocessSpec(height=16, width=16)


@BENCHMARKS.register("_test_llmskill")
class Toy(Benchmark):
    """Three items whose user turn names the item."""

    def items(self, split: str) -> list[Item]:
        """The same three items for every split.

        Args:
            split: Ignored.

        Returns:
            Three items whose gold answer is yes.
        """
        return [Item(id=f"i{i}", target="yes", ground_truth="yes") for i in range(3)]

    def build_messages(
        self, item: Item, with_image: bool, site: str = "pre_query"
    ) -> list[dict[str, object]]:
        """The configured system turn, then the item's question.

        Args:
            item: Item to build the prompt for.
            with_image: Whether to reserve an image slot.
            site: Injection site for the image.

        Returns:
            Chat messages for the item.
        """
        query = {"role": "user", "content": [{"type": "text", "text": f"question {item.id}"}]}
        messages = [*self.system_messages(), query]
        return inject_image(messages, site) if with_image else messages

    def score(self, output: str, item: Item) -> float:
        """Whether the output is the gold answer.

        Args:
            output: Text generated by the model.
            item: Item the output was generated for.

        Returns:
            1.0 on a match, 0.0 otherwise.
        """
        return float(output == item.ground_truth)


