def test_training_shows_the_skill_exactly_where_eval_shows_it(tmp_path: Path) -> None:
    """Every training prompt is one skillpng_conditioned sends with the same skill.

    Args:
        tmp_path: Directory for the skill, the run and the results.
    """
    skill_path = _skill_file(tmp_path, f"\n{SKILL}\n\n")
    cfg = _train_config(tmp_path, skill_path=skill_path)
    learner = Learner()

    Trainer(cfg, model=learner).run()

    composed = compose_system_prompt(PROMPT, cfg.injection.skill_template, SKILL)
    system = {"role": "system", "content": composed}
    assert learner.seen and all(messages[0] == system for messages in learner.seen)
    # The clean baseline is the skill alone, without the image.
    assert any(image is None for image in learner.images)

    recorder = Recorder()
    best = str(tmp_path / "runs" / "t" / "best.png")
    row = run_eval(
        _config(
            tmp_path, condition="skillpng_conditioned", image_path=best, skill_path=skill_path
        ),
        model=recorder,
    )
    shown = [m for m, image in zip(learner.seen, learner.images, strict=True) if image is not None]
    assert shown and all(messages in recorder.seen for messages in shown)
    assert row.condition == "skillpng_conditioned"
    assert row.skill_digest == hashlib.sha256(SKILL.encode()).hexdigest()
    assert (tmp_path / "runs" / "t" / "eval" / "test-skillpng_conditioned.jsonl").exists()


def test_skillpng_conditioned_refuses_an_image_not_trained_under_the_skill(
    tmp_path: Path,
) -> None:
    """An image trained without a skill, or under another one, is refused.

    Checked before the model is built: none is passed, and the config's hf
    backend with no checkpoint would fail on its own otherwise.

    Args:
        tmp_path: Directory for the skills, the images and the runs.
    """
    skill_path = _skill_file(tmp_path)
    other = tmp_path / "other.md"
    other.write_text("Answer no whenever unsure.")
    Trainer(_train_config(tmp_path, run_name="plain"), model=Learner()).run()
    Trainer(_train_config(tmp_path, run_name="other", skill_path=str(other)), model=Learner()).run()
    untrained, _ = _image_file(tmp_path)
    runs = tmp_path / "runs"

    for image_path in (
        str(runs / "plain" / "best.png"),
        str(runs / "other" / "best.png"),
        untrained,
    ):
        cfg = _config(
            tmp_path,
            condition="skillpng_conditioned",
            image_path=image_path,
            skill_path=skill_path,
        )
        with pytest.raises(ValueError, match="was optimized under skill"):
            run_eval(cfg)

    unset = _config(tmp_path, condition="skillpng_conditioned", skill_path=skill_path)
    with pytest.raises(ValueError, match=r"skillpng_conditioned requires eval\.image_path"):
        run_eval(unset)


def test_the_checkpoint_names_the_skill_it_was_trained_under(tmp_path: Path) -> None:
    """The sidecar carries the skill's path and digest, and nulls without one.

    Args:
        tmp_path: Directory for the skill and the runs.
    """
    skill_path = _skill_file(tmp_path)
    Trainer(_train_config(tmp_path, skill_path=skill_path), model=Learner()).run()
    plain = Learner()
    Trainer(_train_config(tmp_path, run_name="plain"), model=plain).run()

    meta = json.loads((tmp_path / "runs" / "t" / "best.json").read_text())
    assert meta["skill_path"] == skill_path
    assert meta["skill_digest"] == hashlib.sha256(SKILL.encode()).hexdigest()
    bare = json.loads((tmp_path / "runs" / "plain" / "best.json").read_text())
    assert (bare["skill_path"], bare["skill_digest"]) == (None, None)
    assert all(_text(messages[0]) == PROMPT for messages in plain.seen)


