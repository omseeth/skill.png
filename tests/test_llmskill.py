def test_the_skill_reaches_the_system_turn_and_the_row(tmp_path: Path) -> None:
    """Every item is asked under the composed prompt, with its user turn unchanged.

    Args:
        tmp_path: Directory for the skill, the run and the results.
    """
    cfg = _config(tmp_path, skill_path=_skill_file(tmp_path, f"\n{SKILL}\n\n"))
    recorder = Recorder()

    row = run_eval(cfg, model=recorder)

    composed = compose_system_prompt(PROMPT, cfg.injection.skill_template, SKILL)
    assert [_text(messages[0]) for messages in recorder.seen] == [composed] * 3
    assert [_text(messages[1]) for messages in recorder.seen] == [
        "question i0",
        "question i1",
        "question i2",
    ]
    assert row.condition == "llmskill"
    assert row.skill_digest == hashlib.sha256(SKILL.encode()).hexdigest()
    assert row.image_digest is None and row.param_kind is None
    [written] = read_rows(tmp_path / "results.jsonl")
    assert written["skill_digest"] == row.skill_digest
    assert not set(IMAGE_FIELDS) & set(written)
    assert (tmp_path / "runs" / "t" / "eval" / "test-llmskill.jsonl").exists()


def test_skillpng_llmskill_sends_the_skill_and_the_image(tmp_path: Path) -> None:
    """The system turn is llmskill's, the user turn is skillpng's.

    Args:
        tmp_path: Directory for the skill, the image, the run and the results.
    """
    image_path, _ = _image_file(tmp_path)
    cfg = _config(
        tmp_path,
        condition="skillpng_llmskill",
        image_path=image_path,
        skill_path=_skill_file(tmp_path),
    )
    recorder = Recorder()

    run_eval(cfg, model=recorder)

    composed = compose_system_prompt(PROMPT, cfg.injection.skill_template, SKILL)
    system = {"role": "system", "content": composed}
    assert [messages[0] for messages in recorder.seen] == [system] * 3
    assert [messages[1]["content"] for messages in recorder.seen] == [
        [{"type": "image"}, {"type": "text", "text": f"question i{i}"}] for i in range(3)
    ]
    shown = load_param(image_path).tensor().detach()
    assert len(recorder.images) == 3
    assert all(
        image is not None and torch.equal(image, shown) for image in recorder.images
    )


def test_a_skillpng_llmskill_row_carries_both_digests(tmp_path: Path) -> None:
    """The row names the image and the skill it was scored under.

    Args:
        tmp_path: Directory for the skill, the image, the run and the results.
    """
    image_path, digest = _image_file(tmp_path)
    cfg = _config(
        tmp_path,
        condition="skillpng_llmskill",
        image_path=image_path,
        skill_path=_skill_file(tmp_path),
    )

    row = run_eval(cfg, model=Recorder())

    skill_digest = hashlib.sha256(SKILL.encode()).hexdigest()
    assert row.condition == "skillpng_llmskill"
    assert row.image_digest == digest and row.param_kind == "full"
    assert row.skill_digest == skill_digest
    [written] = read_rows(tmp_path / "results.jsonl")
    assert (written["image_digest"], written["skill_digest"]) == (digest, skill_digest)
    eval_dir = tmp_path / "runs" / "t" / "eval"
    assert (eval_dir / "test-skillpng_llmskill.jsonl").exists()


@pytest.mark.parametrize("condition", ["llmskill", "skillpng_llmskill"])
def test_a_prebuilt_benchmark_must_already_carry_the_skill(
    tmp_path: Path, condition: str
) -> None:
    """Otherwise the skill would be dropped without a word.

    Args:
        tmp_path: Directory for the skill, the image, the run and the results.
        condition: A condition that sends the skill.
    """
